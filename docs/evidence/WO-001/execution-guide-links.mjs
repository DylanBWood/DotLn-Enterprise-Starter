// Lists every distinct relative link target in the exported execution guide,
// whether it exists in this launchpad, and whether UPSTREAM.md lists it among
// the core documents the kit points to without carrying. Run from the
// repository root:
//
//   node docs/evidence/WO-001/execution-guide-links.mjs > docs/evidence/WO-001/execution-guide-links.txt
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, normalize } from "node:path";

const guide = "docs/product/07-execution-guide.md";
const upstream = readFileSync("UPSTREAM.md", "utf8");
const targets = [
  ...new Set(
    [...readFileSync(guide, "utf8").matchAll(/\]\(([^)#: ]+)[)#]/g)].map(
      (match) => match[1],
    ),
  ),
].sort();
const rows = targets.map((target) => {
  const resolved = normalize(join(dirname(guide), target));
  return [
    target,
    existsSync(resolved) ? "exists" : "missing",
    upstream.includes(resolved) ? "listed" : "unlisted",
  ];
});
const missing = rows.filter((row) => row[1] === "missing");
const unlisted = missing.filter((row) => row[2] === "unlisted");
console.log(
  [
    `# Relative link targets in ${guide}, resolved from its directory.`,
    "# Columns: target, exists|missing in this launchpad, listed|unlisted among UPSTREAM.md pointers.",
    "# Generated by: node docs/evidence/WO-001/execution-guide-links.mjs > docs/evidence/WO-001/execution-guide-links.txt",
    `# Distinct targets ${targets.length}; missing ${missing.length}; missing and unlisted ${unlisted.length}.`,
    ...rows.map((row) => row.join("\t")),
  ].join("\n"),
);
